static int valid(const HCLaunchRequest *v){
 if(!v||strnlen(v->game,sizeof v->game)!=11||memcmp(v->game,"CLV-U-",6)||strnlen(v->digest,sizeof v->digest)!=64||!v->epoch)return 0;
 for(size_t i=6;i<11;i++)if(!((v->game[i]>='A'&&v->game[i]<='Z')||(v->game[i]>='0'&&v->game[i]<='9')))return 0;
 for(size_t i=0;i<64;i++)if(!((v->digest[i]>='a'&&v->digest[i]<='f')||(v->digest[i]>='0'&&v->digest[i]<='9')))return 0;
 unsigned char nonzero=0;for(size_t i=0;i<16;i++)nonzero|=v->session[i];return nonzero!=0;
}
int hc_launch_request_encode(const HCLaunchRequest *v,unsigned char out[HC_LAUNCH_REQUEST_SIZE]){
 if(!out||!valid(v)){errno=EINVAL;return -1;}unsigned char b[HC_LAUNCH_REQUEST_SIZE];memcpy(b,"HCLREQ1\0",8);memcpy(b+8,v->game,11);memcpy(b+19,v->digest,64);memcpy(b+83,v->session,16);for(unsigned i=0;i<8;i++)b[99+i]=(unsigned char)(v->epoch>>(8*i));memcpy(out,b,sizeof b);return 0;
}
int hc_launch_request_decode(const unsigned char *b,size_t n,HCLaunchRequest *out){
 if(!b||!out||n!=HC_LAUNCH_REQUEST_SIZE||memcmp(b,"HCLREQ1\0",8)){errno=EINVAL;return -1;}HCLaunchRequest v={0};memcpy(v.game,b+8,11);memcpy(v.digest,b+19,64);memcpy(v.session,b+83,16);for(unsigned i=0;i<8;i++)v.epoch|=(uint64_t)b[99+i]<<(8*i);if(!valid(&v)){errno=EINVAL;return -1;}*out=v;return 0;
}
static int is_pipe(int fd,int mode){struct stat st;int f=fcntl(fd,F_GETFL);return f>=0&&(f&O_ACCMODE)==mode&&(f&O_NONBLOCK)&&!fstat(fd,&st)&&S_ISFIFO(st.st_mode);}
/* Suppress only the SIGPIPE generated by this write. Preserve a signal that
 * was already pending for the caller; never change the process-wide handler. */
static int send_frame(int fd,const unsigned char b[HC_LAUNCH_REQUEST_SIZE]){
 sigset_t set,old,pending;int rc;ssize_t n=-1;int saved=0;
 if(sigemptyset(&set)||sigaddset(&set,SIGPIPE))return -1;
 rc=pthread_sigmask(SIG_BLOCK,&set,&old);if(rc){errno=rc;return -1;}
 if(sigpending(&pending)){saved=errno;goto restore;}
 int already=sigismember(&pending,SIGPIPE);if(already<0){saved=errno;goto restore;}
 do n=write(fd,b,HC_LAUNCH_REQUEST_SIZE);while(n<0&&errno==EINTR);
 saved=n<0?errno:(n==(ssize_t)HC_LAUNCH_REQUEST_SIZE?0:EIO);
 if(n<0&&saved==EPIPE&&!already){
  if(sigpending(&pending)){saved=errno;goto restore;}
  int pending_now=sigismember(&pending,SIGPIPE);
  if(pending_now<0){saved=errno;goto restore;}
  if(pending_now){int signal_number=0;rc=sigwait(&set,&signal_number);if(rc||signal_number!=SIGPIPE){saved=rc?rc:EIO;goto restore;}}
 }
restore:
 rc=pthread_sigmask(SIG_SETMASK,&old,NULL);if(rc&&!saved)saved=rc;
 if(saved){errno=saved;return -1;}return 0;
}
int hc_launch_request_send(int fd,const HCLaunchRequest *v){unsigned char b[HC_LAUNCH_REQUEST_SIZE];if(!is_pipe(fd,O_WRONLY)||hc_launch_request_encode(v,b)){errno=EINVAL;return -1;}return send_frame(fd,b);}
static int receive_frame(int fd,unsigned timeout,unsigned char b[HC_LAUNCH_REQUEST_SIZE]){
 if(!b||!timeout||timeout>60000||!is_pipe(fd,O_RDONLY)){errno=EINVAL;return -1;}struct timespec start,now;if(clock_gettime(CLOCK_MONOTONIC,&start))return -1;size_t have=0;
 while(have<HC_LAUNCH_REQUEST_SIZE){if(clock_gettime(CLOCK_MONOTONIC,&now))return -1;int64_t ms=(now.tv_sec-start.tv_sec)*1000+(now.tv_nsec-start.tv_nsec)/1000000;if(ms<0||ms>=(int64_t)timeout){errno=ETIMEDOUT;return -1;}int left=(int)((int64_t)timeout-ms);struct pollfd p={fd,POLLIN|POLLHUP,0};int result=poll(&p,1,left);if(result<0){if(errno==EINTR)continue;return -1;}if(!result){errno=ETIMEDOUT;return -1;}if(p.revents&(POLLERR|POLLNVAL)){errno=EIO;return -1;}ssize_t n=read(fd,b+have,HC_LAUNCH_REQUEST_SIZE-have);if(n>0){have+=(size_t)n;continue;}if(n<0&&(errno==EINTR||errno==EAGAIN||errno==EWOULDBLOCK))continue;errno=EPIPE;return -1;}
 return 0;
}
int hc_launch_request_receive(int fd,unsigned timeout,HCLaunchRequest *out){
 unsigned char b[HC_LAUNCH_REQUEST_SIZE];if(!out){errno=EINVAL;return -1;}if(receive_frame(fd,timeout,b))return -1;return hc_launch_request_decode(b,sizeof b,out);
}
int hc_launch_release_send(int fd,const HCLaunchRequest *expected){
 unsigned char b[HC_LAUNCH_REQUEST_SIZE];if(!is_pipe(fd,O_WRONLY)||hc_launch_request_encode(expected,b)){errno=EINVAL;return -1;}memcpy(b,"HCREL1\0",8);return send_frame(fd,b);
}
int hc_launch_release_receive(int fd,unsigned timeout,const HCLaunchRequest *expected){
 unsigned char b[HC_LAUNCH_REQUEST_SIZE],canonical[HC_LAUNCH_REQUEST_SIZE];
 if(hc_launch_request_encode(expected,canonical))return -1;
 if(receive_frame(fd,timeout,b))return -1;
 memcpy(canonical,"HCREL1\0",8);
 if(memcmp(b,canonical,sizeof b)){errno=EPROTO;return -1;}return 0;
}
