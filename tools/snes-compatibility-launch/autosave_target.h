#ifndef HAKCHI_AUTOSAVE_TARGET_H
#define HAKCHI_AUTOSAVE_TARGET_H
#include <stddef.h>
#include <sys/types.h>
#include <stdint.h>
typedef struct {int parent,workspace,temporary;uid_t owner;int ready,consumed,owns_fds,busy;char identity[1024],destination[128],temp_name[128],workspace_name[44];} HCAutosaveTarget;
#define HC_AUTOSAVE_TARGET_INITIALIZER {0}
/* Single-use. This target object and descriptors remain borrowed, alive, stable and exclusively controlled
 * through completion, and are close-on-exec. Identity's parent is checked
 * against the held parent descriptor. Caller must authenticate game identity,
 * keep that pathname stable, establish private directories on one filesystem, and retain
 * workspace/previous for recovery. No general path trust is inferred here. */
int hc_autosave_target_init(HCAutosaveTarget *,int parent,int workspace,int temporary,uid_t owner,const char *identity,const char *destination,const char *temp_name);
/* Creates a private single-use workspace and temporary file under parent.
 * nonce must be freshly generated by a cryptographically secure source. On
 * failure a newly created workspace may remain for inspection; never removes
 * files. Close only after all async work and recovery inspection have ended. */
int hc_autosave_target_prepare(HCAutosaveTarget *,int parent,uid_t owner,const uint8_t nonce[16],const char *identity,const char *destination);
int hc_autosave_target_close(HCAutosaveTarget *);
/* Main-thread lifecycle: acquire before scheduling a worker and release only
 * from its completion callback. This does not prevent outside close(2) calls. */
int hc_autosave_target_acquire(HCAutosaveTarget *);
int hc_autosave_target_release(HCAutosaveTarget *);
/* 0 is durably published; -1 is failure before linking; -2 is post-rename
 * uncertainty; -3 means the old save remains active but its recovery link
 * needs inspection/cleanup.
 * A mismatched identity is refused before consuming the target. */
int hc_autosave_target_write(HCAutosaveTarget *,const char *identity,const void *bytes,size_t size);
#endif
